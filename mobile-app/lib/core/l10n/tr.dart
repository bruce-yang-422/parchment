/// Interface text in eight languages, keyed by the Traditional Chinese
/// original (the same approach as the web version's i18n.js).
///
/// `tr('找不到「{name}」', {'name': file})` returns the text in the
/// current [AppLocale], with `{placeholders}` filled in. Text missing from
/// the table is shown as written; `test/l10n_test.dart` checks that every
/// `tr()` call has all seven translations.
library;

import '../models/reader_preferences.dart';

/// The interface language, set by the reader controller whenever it
/// changes. Plain code (errors, file locations) reads it too, so it is not
/// tied to a widget.
abstract final class AppLocale {
  static ReaderLocale current = ReaderLocale.zhTw;
}

String tr(String zhTw, [Map<String, Object?> args = const {}]) {
  var text = zhTw;
  final index = AppLocale.current.index;
  if (index > 0) {
    final row = translations[zhTw];
    if (row != null) text = row[index - 1];
  }
  args.forEach((key, value) => text = text.replaceAll('{$key}', '$value'));
  return text;
}

