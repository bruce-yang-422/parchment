import { createHash } from 'node:crypto';
import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const required = [
  'index.html',
  'manifest.webmanifest',
  'assets/favicon.ico',
  'icons/pwa-icon-192x192.png',
  'icons/pwa-icon-512x512.png',
];

const discovered = [
  ...await walk('assets/css', file => file.endsWith('.css')),
  ...await walk('assets/js', file => file.endsWith('.js')),
  ...await walk('assets/vendor', file => {
    if (file.includes('/licenses/')) return false;
    if (file.includes('/katex/fonts/')) return file.endsWith('.woff2');
    return file.endsWith('.js') || file.endsWith('.css');
  }),
];

const files = [...new Set([...required, ...discovered])].sort();
const hash = createHash('sha256');
for (const file of files) {
  const contents = await readFile(path.join(root, ...file.split('/')));
  hash.update(file);
  hash.update(contents);
}

const version = hash.digest('hex').slice(0, 12);
const urls = ['./', ...files.map(file => `./${file}`)];
const source = `/* Generated by scripts/build-pwa.mjs. */
const CACHE_PREFIX = 'parchment-';
const CACHE_NAME = CACHE_PREFIX + '${version}';
const APP_SHELL = './index.html';
const PRECACHE_URLS = ${JSON.stringify(urls, null, 2)};

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then(cache => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(
        keys
          .filter(key => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME)
          .map(key => caches.delete(key))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', event => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then(response => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then(cache => cache.put(request, copy));
          return response;
        })
        .catch(() => caches.match(request).then(cached => cached || caches.match(APP_SHELL)))
    );
    return;
  }

  event.respondWith(
    caches.match(request).then(cached => cached || fetch(request).then(response => {
      if (response.ok) {
        const copy = response.clone();
        caches.open(CACHE_NAME).then(cache => cache.put(request, copy));
      }
      return response;
    }))
  );
});
`;

await writeFile(path.join(root, 'service-worker.js'), source, 'utf8');
console.log(`service-worker.js: ${files.length} assets, cache ${version}`);

async function walk(relativeDirectory, include) {
  const directory = path.join(root, ...relativeDirectory.split('/'));
  const entries = await readdir(directory, { withFileTypes: true });
  const output = [];

  for (const entry of entries) {
    const relative = `${relativeDirectory}/${entry.name}`;
    if (entry.isDirectory()) {
      output.push(...await walk(relative, include));
    } else if (entry.isFile() && include(relative)) {
      const details = await stat(path.join(root, ...relative.split('/')));
      if (details.size > 0) output.push(relative);
    }
  }
  return output;
}
